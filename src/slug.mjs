export function slugify(input, maxWords = 5) {
  let s = String(input)
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^ -~]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-');

  const words = s.split('-').filter((w) => w.length > 0 && !STOP_WORDS.has(w));

  if (words.length === 0) return 'untitled';

  return words.slice(0, maxWords).join('-');
}
